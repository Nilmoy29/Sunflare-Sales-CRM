#!/usr/bin/env node
/** Regenerate src/types/supabase.generated.ts via Supabase MCP */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = execFileSync("node", [join(root, "scripts/mcp-call.mjs"), "generate_typescript_types", "{}"], {
  encoding: "utf8",
});
const parsed = JSON.parse(raw);
const types = parsed.types;
if (!types) {
  console.error("Unexpected MCP response:", raw.slice(0, 200));
  process.exit(1);
}

const header = `/**
 * Generated by Supabase MCP — do not edit manually.
 * Regenerate: npm run db:types
 */
`;

const outPath = join(root, "src/types/supabase.generated.ts");
writeFileSync(outPath, header + types + "\n");
console.log("Wrote", outPath);
